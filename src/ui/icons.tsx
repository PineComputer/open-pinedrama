export type IconName = keyof typeof ICONS;

/** An icon beside words that say the same, so it is hidden from assistive technology. */
export function Icon({ name, className }: { name: IconName; className?: string }) {
  const Glyph = ICONS[name];
  return <Glyph className={className ? `ds-icon ${className}` : "ds-icon"} aria-hidden="true" focusable="false" />;
}

