export type Lang = "en" | "zh";
const dictionaries: Record<Lang, Record<Key, string>> = { en, zh };

function initial(): Lang {
  try {
    const saved = localStorage.getItem("studio.lang");
    if (saved === "en" || saved === "zh") return saved;
  } catch {
    // storage may be unavailable; fall back to the browser's language
  }
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

let current: Lang = initial();
document.documentElement.lang = current === "zh" ? "zh-CN" : "en";
const listeners = new Set<() => void>();

export function setLang(lang: Lang): void {
  current = lang;
  try {
    localStorage.setItem("studio.lang", lang);
  } catch {
    // not saved; the choice lasts this visit
  }
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  for (const listener of listeners) listener();
}

export type TKey = Key;

export function useT(): { t: (key: Key, vars?: Record<string, string | number>) => string; lang: Lang } {
  const [, setTick] = useState(0);
  useEffect(() => {
    const update = () => setTick((n) => n + 1);
    listeners.add(update);
    return () => void listeners.delete(update);
  }, []);
  const t = (key: Key, vars?: Record<string, string | number>) =>
    (dictionaries[current][key] ?? en[key]).replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? ""));
  return { t, lang: current };
}
